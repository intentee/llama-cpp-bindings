#[llama_test(
    model_source = HuggingFace("unsloth/Qwen3.6-35B-A3B-GGUF", "Qwen3.6-35B-A3B-UD-Q4_K_M.gguf"),
    n_gpu_layers = 999,
    load_mode = Mmap,
    n_ctx = 512,
    n_batch = 512,
    n_ubatch = 128,
)]
fn a_loaded_state_file_restores_the_tokens_it_was_saved_with(
    fixture: &LlamaFixture<'_>,
) -> Result<()> {
    let mut context = fixture.build_context()?;

    let tokens =
        fixture
            .model
            .str_to_token("Hello world", AddBos::Always, ParseSpecialTokens::Always)?;
    let mut batch = LlamaBatch::new(ContextLimits::of(&context));
    batch.add_sequence(&tokens, 0, false)?;
    context.decode(&batch)?;

    let session_path = env::temp_dir().join("llama_test_session.bin");
    context.state_save_file(&session_path, &tokens)?;

    let loaded_tokens = context.state_load_file(&session_path, 512)?;
    assert_eq!(loaded_tokens, tokens);

    fs::remove_file(&session_path)?;

    Ok(())
}

