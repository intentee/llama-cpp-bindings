#[llama_test(
    model_source = HuggingFace("unsloth/Qwen3.6-35B-A3B-GGUF", "Qwen3.6-35B-A3B-UD-Q4_K_M.gguf"),
    n_gpu_layers = 999,
    load_mode = Mmap,
    n_ctx = 512,
    n_batch = 128,
    n_ubatch = 64,
)]
fn chat_template_with_nonexistent_name_returns_error(fixture: &LlamaFixture<'_>) {
    let result = fixture
        .model
        .chat_template(Some("nonexistent_template_name_xyz"));
    assert_eq!(result.unwrap_err(), ChatTemplateError::MissingTemplate);
}

#[llama_test(
    model_source = HuggingFace("unsloth/Qwen3.5-0.8B-GGUF", "Qwen3.5-0.8B-Q4_K_M.gguf"),
    n_gpu_layers = 999,
    load_mode = Mmap,
    n_ctx = 512,
    n_batch = 128,
    n_ubatch = 64,
)]
fn chat_template_with_a_nul_byte_in_the_name_returns_error(fixture: &LlamaFixture<'_>) {
    assert_eq!(
        fixture.model.chat_template(Some("tool\0use")).err(),
        CString::new("tool\0use")
            .err()
            .map(ChatTemplateError::NullError)
    );
}
