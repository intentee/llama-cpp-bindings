fn n_vocab_matches_tokens_iterator_count(fixture: &LlamaFixture<'_>) -> Result<()> {
    let model = fixture.model;
    let n_vocab = model.n_vocab();
    let count = model.tokens(false).count();

    assert_eq!(count, usize::try_from(n_vocab)?);
    Ok(())
}
