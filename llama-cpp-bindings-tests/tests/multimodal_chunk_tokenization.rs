fn tokenizing_reports_a_chunk_list_llama_cpp_cannot_allocate(
    &LlamaFixture { mtmd_context, .. }: &LlamaFixture<'_>,
) -> Result<()> {
    let mtmd_ctx = mtmd_context.context("mmproj_file declared in attribute")?;
    let _fault = ArmedFault::at(
        llama_cpp_bindings_sys::bindings::LLAMA_RS_FAULT_POINT_MTMD_INPUT_CHUNKS_INIT_THROWS,
    );

    ensure!(
        MtmdInputChunks::tokenize(
            mtmd_ctx,
            MtmdInputText {
                text: "Hello".to_owned(),
                add_special: true,
                parse_special: true,
            },
            &[],
        )
        .err()
            == Some(MtmdError::TokenizeInputChunks(Box::new(
                MtmdError::InputChunksReported {
                    message: injected_fault_message()?,
                }
            )))
    );

    Ok(())
}
