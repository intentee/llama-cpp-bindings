fn first_image_chunk<'chunks, 'context>(
    chunks: &'chunks MtmdInputChunks<'context>,
) -> Result<MtmdInputChunkView<'chunks, 'context>> {
    chunks
        .chunks()
        .into_iter()
        .find(|chunk| chunk.chunk_type() == Ok(MtmdInputChunkType::Image))
        .context("a prompt with an image must tokenize into an image chunk")
}

